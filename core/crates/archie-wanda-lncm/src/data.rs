//! Datasets: what the trainer reads and what the distillation pipeline asks teachers about.
//!
//! Everything here is JSON Lines with closed schemas. Two rules hold for every record:
//!
//! - **Provenance is owned or public.** An example comes from an owned generator, from a public
//!   dataset whose licence is named, or from a teacher's answer to such a case. Nothing from a
//!   person's own chats is ever a training example or a teacher's prompt.
//! - **Benchmarks stay out.** FANToM, OpenToM and any other evaluation set are for measuring
//!   only; [`EvalGuard`] drops cases that share long word sequences with them.

use crate::{bounded_text, Lang, LncmError, Result, Task};
use serde::de::DeserializeOwned;
use serde::{Deserialize, Serialize};
use std::collections::HashSet;
use std::io::{BufRead, Write};
use std::path::Path;

pub const MAX_LINE_BYTES: usize = 256 * 1024;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Split {
    Train,
    Dev,
}

/// Deterministic split by family id: a world, a dialogue or a source document never crosses.
pub fn split_for(family: &str, dev_share: f32) -> Split {
    let digest = crate::sha256_hex(family.as_bytes());
    let bucket = u32::from_str_radix(&digest[..8], 16).unwrap_or(0) as f64 / f64::from(u32::MAX);
    if bucket < f64::from(dev_share) {
        Split::Dev
    } else {
        Split::Train
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case", deny_unknown_fields)]
pub enum Provenance {
    /// Generated by owned code from a seed: labels are exact.
    OwnedProcedural { generator: String, seed: u64 },
    /// A public dataset, by name, revision and licence.
    PublicLicensed {
        dataset: String,
        revision: String,
        license: String,
    },
    /// A teacher's answer to an owned or public case.
    Distilled { teacher: String, case_id: String },
}

impl Provenance {
    fn valid(&self) -> bool {
        match self {
            Provenance::OwnedProcedural { generator, .. } => bounded_text(generator, 128),
            Provenance::PublicLicensed {
                dataset,
                revision,
                license,
            } => {
                bounded_text(dataset, 128)
                    && bounded_text(revision, 128)
                    && bounded_text(license, 64)
            }
            Provenance::Distilled { teacher, case_id } => {
                bounded_text(teacher, 128) && bounded_text(case_id, 192)
            }
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Choice {
    Option(usize),
    Abstain,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Target {
    #[serde(default)]
    pub gate: Option<bool>,
    #[serde(default)]
    pub yes_no: Option<bool>,
    #[serde(default)]
    pub change: Option<bool>,
    #[serde(default)]
    pub choice: Option<Choice>,
    #[serde(default)]
    pub plan: Option<String>,
    /// The answer (compose) or the delta lines (update).
    #[serde(default)]
    pub text: Option<String>,
}

/// One supervised example.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Example {
    pub id: String,
    pub task: Task,
    pub lang: Lang,
    pub split: Split,
    /// The adapter this example trains, for the adapter stage.
    #[serde(default)]
    pub adapter: Option<String>,
    #[serde(default)]
    pub question: Option<String>,
    #[serde(default)]
    pub options: Vec<String>,
    #[serde(default)]
    pub state: Option<String>,
    #[serde(default)]
    pub chunk: Option<String>,
    #[serde(default)]
    pub draft: Option<String>,
    pub target: Target,
    pub provenance: Provenance,
    #[serde(default = "one")]
    pub weight: f32,
}

fn one() -> f32 {
    1.0
}

fn opt_text(value: &Option<String>, max: usize) -> bool {
    value.as_deref().is_none_or(|v| bounded_text(v, max))
}

impl Example {
    pub fn validate(&self) -> Result<()> {
        let fail = |why: &str| Err(LncmError::Data(format!("{}: {why}", self.id)));
        if !bounded_text(&self.id, 192) || !self.provenance.valid() {
            return fail("id or provenance");
        }
        if !(0.0..=100.0).contains(&self.weight) || self.weight.is_nan() {
            return fail("weight");
        }
        if !opt_text(&self.question, 2000)
            || !opt_text(&self.state, 32_000)
            || !opt_text(&self.chunk, 16_000)
            || !opt_text(&self.draft, 16_000)
            || !opt_text(&self.target.plan, 1000)
            || !opt_text(&self.target.text, 8000)
            || self.options.len() > 16
            || self.options.iter().any(|o| !bounded_text(o, 300))
            || self
                .adapter
                .as_deref()
                .is_some_and(|a| !crate::model::adapter_name_valid(a))
        {
            return fail("a field is out of bounds");
        }
        let t = &self.target;
        let ok = match self.task {
            Task::Gate => self.question.is_some() && t.gate.is_some(),
            Task::Update => self.chunk.is_some() && t.change.is_some() && t.text.is_some(),
            Task::Decide => {
                self.question.is_some()
                    && !self.options.is_empty()
                    && match t.choice {
                        Some(Choice::Option(i)) => i < self.options.len(),
                        Some(Choice::Abstain) => true,
                        None => false,
                    }
            }
            Task::Compose => self.question.is_some() && t.text.is_some(),
        };
        if !ok {
            return fail("the task's inputs or target are missing");
        }
        Ok(())
    }
}

/// A question for teachers. `gold` holds exact labels when a simulator knows them.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Case {
    pub id: String,
    pub task: Task,
    pub lang: Lang,
    pub split: Split,
    #[serde(default)]
    pub adapter: Option<String>,
    #[serde(default)]
    pub question: Option<String>,
    #[serde(default)]
    pub options: Vec<String>,
    #[serde(default)]
    pub state: Option<String>,
    #[serde(default)]
    pub chunk: Option<String>,
    #[serde(default)]
    pub gold: Option<Target>,
    pub provenance: Provenance,
}

impl Case {
    pub fn validate(&self) -> Result<()> {
        if matches!(self.provenance, Provenance::Distilled { .. }) {
            return Err(LncmError::Data(format!(
                "{}: a case must come from an owned or public source",
                self.id
            )));
        }
        if self.task == Task::Gate {
            return Err(LncmError::Data(format!(
                "{}: gate labels are not distilled",
                self.id
            )));
        }
        self.as_example(self.gold.clone().unwrap_or_default())
            .validate_inputs()
    }

    /// The example this case becomes with `target`.
    pub fn as_example(&self, target: Target) -> Example {
        Example {
            id: self.id.clone(),
            task: self.task,
            lang: self.lang,
            split: self.split,
            adapter: self.adapter.clone(),
            question: self.question.clone(),
            options: self.options.clone(),
            state: self.state.clone(),
            chunk: self.chunk.clone(),
            draft: None,
            target,
            provenance: self.provenance.clone(),
            weight: 1.0,
        }
    }

    /// Every text a teacher would be shown.
    pub fn texts(&self) -> Vec<&str> {
        let mut out: Vec<&str> = [&self.question, &self.state, &self.chunk]
            .into_iter()
            .filter_map(|t| t.as_deref())
            .collect();
        out.extend(self.options.iter().map(String::as_str));
        out
    }
}

impl Example {
    /// Bounds and provenance only, without requiring a target (for cases).
    fn validate_inputs(&self) -> Result<()> {
        let mut probe = self.clone();
        // Fill the target so the task check passes; only inputs are being checked.
        probe.target = Target {
            gate: Some(true),
            yes_no: None,
            change: Some(true),
            choice: Some(Choice::Abstain),
            plan: None,
            text: Some("-".into()),
        };
        probe.validate()
    }
}

pub fn read_jsonl<T: DeserializeOwned>(path: &Path, max_records: usize) -> Result<Vec<T>> {
    let file = std::fs::File::open(path)?;
    let mut reader = std::io::BufReader::new(file);
    let mut out = Vec::new();
    let mut line = String::new();
    let mut number = 0usize;
    loop {
        line.clear();
        let n = std::io::Read::take(&mut reader, MAX_LINE_BYTES as u64 + 1).read_line(&mut line)?;
        if n == 0 {
            break;
        }
        number += 1;
        if line.len() > MAX_LINE_BYTES {
            return Err(LncmError::Data(format!(
                "{}:{number}: line too long",
                path.display()
            )));
        }
        if line.trim().is_empty() {
            continue;
        }
        if out.len() >= max_records {
            return Err(LncmError::Data(format!(
                "{}: more than {max_records} records",
                path.display()
            )));
        }
        out.push(
            serde_json::from_str(line.trim_end())
                .map_err(|e| LncmError::Data(format!("{}:{number}: {e}", path.display())))?,
        );
    }
    Ok(out)
}

pub fn write_jsonl<T: Serialize>(path: &Path, records: &[T]) -> Result<()> {
    let tmp = path.with_extension("jsonl.tmp");
    {
        let mut file = std::io::BufWriter::new(std::fs::File::create(&tmp)?);
        for r in records {
            serde_json::to_writer(&mut file, r)?;
            file.write_all(b"\n")?;
        }
        file.flush()?;
    }
    std::fs::rename(tmp, path)?;
    Ok(())
}

pub fn append_jsonl<T: Serialize>(path: &Path, record: &T) -> Result<()> {
    let mut file = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(path)?;
    let mut line = serde_json::to_vec(record)?;
    line.push(b'\n');
    file.write_all(&line)?;
    Ok(())
}

/// Reads and validates training examples.
pub fn load_examples(path: &Path) -> Result<Vec<Example>> {
    let examples: Vec<Example> = read_jsonl(path, 10_000_000)?;
    let mut ids = HashSet::new();
    for e in &examples {
        e.validate()?;
        if !ids.insert(e.id.as_str()) {
            return Err(LncmError::Data(format!("duplicate example id {}", e.id)));
        }
    }
    Ok(examples)
}

pub fn load_cases(path: &Path) -> Result<Vec<Case>> {
    let cases: Vec<Case> = read_jsonl(path, 10_000_000)?;
    let mut ids = HashSet::new();
    for c in &cases {
        c.validate()?;
        if !ids.insert(c.id.as_str()) {
            return Err(LncmError::Data(format!("duplicate case id {}", c.id)));
        }
    }
    Ok(cases)
}

/// Shared word n-grams with evaluation-only sets.
pub struct EvalGuard {
    grams: HashSet<u64>,
    n: usize,
}

impl EvalGuard {
    pub fn new(n: usize) -> Self {
        Self {
            grams: HashSet::new(),
            n: n.max(3),
        }
    }

    pub fn add_text(&mut self, text: &str) {
        for g in word_grams(text, self.n) {
            self.grams.insert(g);
        }
    }

    /// Adds every file given, read as text (JSON is fine: its words are what matters).
    pub fn add_files(&mut self, paths: &[std::path::PathBuf]) -> Result<()> {
        for path in paths {
            let text = crate::codec::read_bounded(path, 1 << 30)?;
            self.add_text(&text);
        }
        Ok(())
    }

    pub fn is_empty(&self) -> bool {
        self.grams.is_empty()
    }

    /// How many of the text's n-grams occur in an evaluation set.
    pub fn overlap(&self, text: &str) -> usize {
        word_grams(text, self.n)
            .into_iter()
            .collect::<HashSet<_>>()
            .into_iter()
            .filter(|g| self.grams.contains(g))
            .count()
    }
}

fn word_grams(text: &str, n: usize) -> Vec<u64> {
    let words: Vec<String> = text
        .split(|c: char| !c.is_alphanumeric())
        .filter(|w| !w.is_empty())
        .map(str::to_lowercase)
        .collect();
    words
        .windows(n)
        .map(|w| {
            // FNV-1a: stable across runs and platforms.
            let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
            for word in w {
                for b in word.bytes().chain(std::iter::once(b' ')) {
                    hash ^= u64::from(b);
                    hash = hash.wrapping_mul(0x0100_0000_01b3);
                }
            }
            hash
        })
        .collect()
}

#[derive(Deserialize)]
struct Tranche {
    format: String,
    provenance: serde_json::Value,
    examples: Vec<TrancheExample>,
}

#[derive(Deserialize)]
struct TrancheExample {
    example_id: String,
    family_id: String,
    split: String,
    #[serde(default)]
    variant: Option<String>,
    lang: String,
    messages: Vec<TrancheMessage>,
    label: String,
}

#[derive(Deserialize)]
struct TrancheMessage {
    role: String,
    content: String,
}

/// Label sets of the owned procedural generator (`tomgen.py`), per language.
const LABEL_SETS: &[(&str, &[&str])] = &[
    ("en", &["yes", "no"]),
    ("es", &["sí", "no"]),
    ("en", &["more", "the same", "less"]),
    ("es", &["más", "lo mismo", "menos"]),
    (
        "en",
        &["more accessible", "equally accessible", "less accessible"],
    ),
    (
        "es",
        &["más accesible", "igual de accesible", "menos accesible"],
    ),
    ("en", &["positive", "neutral", "negative"]),
    ("es", &["positiva", "neutral", "negativa"]),
];

/// Imports a `chat-v1` tranche written by the Python generator. Labels from a closed set become
/// decisions over that set; any other label (a container, a list of names) becomes a composed
/// answer whose gold text is the label.
pub fn import_tranche(path: &Path) -> Result<Vec<Case>> {
    let tranche: Tranche = serde_json::from_str(&crate::codec::read_bounded(path, 1 << 30)?)?;
    if tranche.format != "chat-v1" {
        return Err(LncmError::Data("not a chat-v1 tranche".into()));
    }
    let kind = tranche
        .provenance
        .get("kind")
        .and_then(|v| v.as_str())
        .unwrap_or("");
    if kind != "owned-procedural" && kind != "owned-synthetic" {
        return Err(LncmError::Data(
            "a tranche must have owned provenance".into(),
        ));
    }
    let generator = tranche
        .provenance
        .get("generator")
        .and_then(|v| v.as_str())
        .unwrap_or("tomgen")
        .to_string();
    let seed = tranche
        .provenance
        .get("seed")
        .and_then(|v| v.as_u64())
        .unwrap_or(0);
    let mut out = Vec::with_capacity(tranche.examples.len());
    for e in tranche.examples {
        let lang = match e.lang.as_str() {
            "es" => Lang::Es,
            "en" => Lang::En,
            _ => continue,
        };
        let Some(user) = e.messages.iter().rev().find(|m| m.role == "user") else {
            continue;
        };
        let (story, question) = match user.content.rsplit_once("\n\n") {
            Some((s, q)) => (Some(s.to_string()), q.to_string()),
            None => (None, user.content.clone()),
        };
        let label = e.label.trim();
        let set = LABEL_SETS
            .iter()
            .find(|(l, set)| *l == e.lang && set.contains(&label))
            .map(|(_, set)| *set);
        let (task, options, gold) = match set {
            Some(set) => (
                Task::Decide,
                set.iter().map(|s| s.to_string()).collect(),
                Target {
                    choice: set.iter().position(|s| *s == label).map(Choice::Option),
                    ..Default::default()
                },
            ),
            None => (
                Task::Compose,
                Vec::new(),
                Target {
                    text: Some(label.to_string()),
                    ..Default::default()
                },
            ),
        };
        let case = Case {
            id: format!("tomgen:{}", e.example_id),
            task,
            lang,
            split: if e.split == "train" {
                Split::Train
            } else {
                Split::Dev
            },
            adapter: None,
            question: Some(question),
            options,
            state: story,
            chunk: None,
            gold: Some(gold),
            provenance: Provenance::OwnedProcedural {
                generator: format!("{generator}:{}", e.variant.as_deref().unwrap_or("?")),
                seed,
            },
        };
        let _ = e.family_id;
        if case.validate().is_ok() {
            out.push(case);
        }
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn decide() -> Example {
        Example {
            id: "x".into(),
            task: Task::Decide,
            lang: Lang::Es,
            split: Split::Train,
            adapter: None,
            question: Some("¿Sabe Pedro lo del viaje?".into()),
            options: vec!["sí".into(), "no".into()],
            state: None,
            chunk: None,
            draft: None,
            target: Target {
                choice: Some(Choice::Option(1)),
                ..Default::default()
            },
            provenance: Provenance::OwnedProcedural {
                generator: "synth".into(),
                seed: 1,
            },
            weight: 1.0,
        }
    }

    #[test]
    fn examples_validate_their_task() {
        decide().validate().unwrap();
        let mut bad = decide();
        bad.target.choice = Some(Choice::Option(2));
        assert!(bad.validate().is_err());
        let mut bad = decide();
        bad.options.clear();
        assert!(bad.validate().is_err());
        let mut bad = decide();
        bad.adapter = Some("../etc".into());
        assert!(bad.validate().is_err());
    }

    #[test]
    fn jsonl_round_trip_and_duplicates_refused() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("e.jsonl");
        write_jsonl(&path, &[decide()]).unwrap();
        assert_eq!(load_examples(&path).unwrap(), vec![decide()]);
        append_jsonl(&path, &decide()).unwrap();
        assert!(load_examples(&path).is_err());
    }

    #[test]
    fn a_distilled_record_is_not_a_case() {
        let case = Case {
            id: "c".into(),
            task: Task::Compose,
            lang: Lang::En,
            split: Split::Train,
            adapter: None,
            question: Some("q".into()),
            options: vec![],
            state: None,
            chunk: None,
            gold: None,
            provenance: Provenance::Distilled {
                teacher: "t".into(),
                case_id: "c0".into(),
            },
        };
        assert!(case.validate().is_err());
    }

    #[test]
    fn eval_guard_finds_shared_sequences_only() {
        let mut guard = EvalGuard::new(5);
        guard.add_text("Sally puts the marble in the basket and leaves the room.");
        assert!(guard.overlap("then sally puts the marble in the basket and goes") >= 2);
        assert_eq!(guard.overlap("Pedro no sabe que el viaje es en julio"), 0);
    }

    #[test]
    fn split_is_stable_and_roughly_proportional() {
        let dev = (0..2000)
            .filter(|i| split_for(&format!("w{i}"), 0.1) == Split::Dev)
            .count();
        assert!((120..=280).contains(&dev), "{dev}");
        assert_eq!(split_for("w1", 0.1), split_for("w1", 0.1));
    }

    #[test]
    fn imports_python_tranches() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("t.json");
        let tranche = serde_json::json!({
            "format": "chat-v1",
            "provenance": {"kind": "owned-procedural", "generator": "tomgen.generate_v3", "seed": 7},
            "examples": [
                {"example_id": "w1:0", "family_id": "w1", "split": "train", "variant": "coarse", "lang": "es",
                 "domain": "personal", "messages": [{"role": "system", "content": "s"}, {"role": "user", "content": "Pedro entra.\n\n¿Cree Pedro que sigue ahí? Responde sí o no."}],
                 "target": "…", "label": "sí", "mode": "think", "pair": null, "side": null},
                {"example_id": "w1:1", "family_id": "w1", "split": "development", "variant": "fine", "lang": "es",
                 "domain": "personal", "messages": [{"role": "user", "content": "Historia.\n\n¿Dónde buscará?"}],
                 "target": "…", "label": "la caja roja", "mode": "direct", "pair": null, "side": null}
            ]
        });
        std::fs::write(&path, tranche.to_string()).unwrap();
        let cases = import_tranche(&path).unwrap();
        assert_eq!(cases.len(), 2);
        assert_eq!(cases[0].task, Task::Decide);
        assert_eq!(
            cases[0].gold.as_ref().unwrap().choice,
            Some(Choice::Option(0))
        );
        assert_eq!(cases[1].task, Task::Compose);
        assert_eq!(cases[1].split, Split::Dev);
        assert_eq!(cases[1].state.as_deref(), Some("Historia."));
    }
}
