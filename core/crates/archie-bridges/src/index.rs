//! `docs/bridges/INDEX.md`: the page a node or a planner reads to learn which applications
//! it can drive by tool, how to connect, and when to use the Stage instead.
//!
//! Generated from the bridges themselves (`archie-bridges index`), and a test fails when
//! the committed page no longer matches, so the page cannot drift from the code.

use crate::{open, Programs, BUILTIN};
use std::fmt::Write;

/// The committed page, compared against [`render`] by the tests.
pub const COMMITTED: &str = include_str!("../../../../docs/bridges/INDEX.md");

pub fn render() -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# Archie bridges\n\n\
         <!-- Generated by `archie-bridges index`. Edit bridges/<id>/bridge.toml or the tools, not this page. -->\n\n\
         A bridge drives one application through its own free, official automation surface — a \
         CLI, its file format, an IPC API — as MCP tools confined to one folder. Read a bridge's \
         guide before its first call: `archie_bridge_guide {{\"bridge\": \"<id>\"}}` over MCP, or \
         `bridges/<id>/SKILL.md`.\n\n\
         ## Connecting\n\n\
         Any MCP client (Claude Code, Codex, an IDE, Archie's own planner) starts the server with \
         the bridges it wants and the folder each works in:\n\n\
         ```bash\n\
         archie-mcp-server --clearance internal --bridge kicad=/home/me/pcb --bridge video=/home/me/media\n\
         ```\n\n\
         Claude Code: `claude mcp add archie -- archie-mcp-server --clearance internal --bridge kicad=$PWD`.\n\
         From a shell, without MCP: `archie-bridges call kicad kicad_projects '{{}}' --workspace DIR`.\n\n\
         `--clearance internal` is needed because these tools carry file names; use it only with a \
         model whose provider's retention you have checked, or a local one.\n\n\
         ## Tools first, eyes second\n\n\
         Use the tools for what they cover: they are exact and cheap. Operate the application's \
         window on the Archie Stage for the rest, and check that work with the bridge's reads and \
         renders instead of by looking. Each bridge says below when the GUI is the way.\n\n\
         ## Bridges\n\n\
         | Bridge | Application | What it does | Programs |\n\
         |---|---|---|---|"
    );
    let scratch = std::env::temp_dir();
    let mut sections = String::new();
    for builtin in BUILTIN {
        let Ok(bridge) = open(builtin.id, &scratch, &Programs::default()) else {
            continue;
        };
        let m = bridge.manifest();
        let _ = writeln!(
            out,
            "| [`{}`](#{}) | [{}]({}) {} | {} | {} |",
            m.id,
            m.id,
            m.app.name,
            m.app.homepage,
            m.app.versions,
            m.summary,
            m.programs
                .iter()
                .map(|p| format!("`{p}`"))
                .collect::<Vec<_>>()
                .join(", ")
        );
        let _ = writeln!(sections, "\n### {}\n\n{}\n", m.id, m.summary);
        let _ = writeln!(sections, "- Works in: {}", m.workspace);
        let _ = writeln!(sections, "- Install on ArchieOS: `{}`", m.install.arch);
        if let Some(ubuntu) = &m.install.ubuntu {
            let _ = writeln!(sections, "- Install on Ubuntu: `{ubuntu}`");
        }
        if let Some(windows) = &m.install.windows {
            let _ = writeln!(sections, "- Install on Windows: `{windows}`");
        }
        let surfaces: Vec<String> = m
            .surfaces
            .iter()
            .map(|s| {
                let planned = if s.status == "planned" {
                    " (planned)"
                } else {
                    ""
                };
                format!("[{}]({}){planned}", s.name, s.doc)
            })
            .collect();
        let _ = writeln!(sections, "- Through: {}", surfaces.join(", "));
        let _ = writeln!(
            sections,
            "- GUI on the Stage (`{}`): {}",
            m.vision.app_ids.join("`, `"),
            m.vision.when
        );
        let _ = writeln!(
            sections,
            "- Guide: [`bridges/{0}/SKILL.md`](../../bridges/{0}/SKILL.md)",
            m.id
        );
        let _ = writeln!(sections, "- End-to-end tests: `{}`\n", m.e2e);
        let _ = writeln!(
            sections,
            "| Tool | Changes files | What it does |\n|---|---|---|"
        );
        for tool in bridge.tools() {
            let writes = if tool.effect == crate::Effect::Writes {
                "yes"
            } else {
                "no"
            };
            let _ = writeln!(sections, "| `{}` | {writes} | {} |", tool.name, tool.title);
        }
    }
    out.push_str(&sections);
    out.push_str(
        "\n## Adding a bridge\n\n\
         Follow [`docs/BRIDGES.md`](../BRIDGES.md): `archie-bridges new <id>` writes the skeleton, \
         and the procedure says what a bridge must have before it is listed here.\n",
    );
    out
}

#[cfg(test)]
mod tests {
    #[test]
    fn the_committed_index_is_current() {
        let fresh = super::render();
        assert!(
            fresh.replace("\r\n", "\n") == super::COMMITTED.replace("\r\n", "\n"),
            "docs/bridges/INDEX.md is stale: run `archie-bridges index` and commit it"
        );
    }
}
